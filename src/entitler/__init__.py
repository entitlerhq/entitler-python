"""The official Entitler SDK for Python.

Ask Entitler whether a customer is entitled to a feature, record metered usage, show pricing and
manage customers' subscriptions, from a server with `EntitlerServer` or `AsyncEntitlerServer`,
or from an app on the customer's device with `EntitlerClient` or `AsyncEntitlerClient`.

Example:
    ```python
    from entitler import EntitlerServer, Feature

    EXPORT_PDF = Feature.boolean("export_pdf")

    with EntitlerServer(os.environ["ENTITLER_KEY"]) as server:
        customer = server.customer(user_id)
        if customer.is_entitled(EXPORT_PDF, default=False):
            export_pdf()
    ```
"""

