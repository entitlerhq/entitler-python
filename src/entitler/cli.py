"""The `entitler` command: feature constants and snapshot keys for your project.

Run `entitler generate` (or `python -m entitler generate`) to write a module of typed feature
constants, and `entitler snapshot-keys` to write the snapshot keys an app ships. The package
never imports this module itself, so apps that do not run the command never load it.
"""

from __future__ import annotations

import ast
import json
import os
import re
import sys
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import TextIO

from ._errors import APIError, EntitlerConnectionError, EntitlerTimeoutError
from ._models import FeatureList, FeatureListing, FeatureType
from ._ops import snapshot_keys

__all__ = ["main", "render_features", "same_features"]

USAGE = """Usage: entitler <command> [options]
       python -m entitler <command> [options]

Commands:
  generate        Writes a Python module of typed feature constants from your Entitler catalogue.
  snapshot-keys   Writes the snapshot keys an app ships, to verify snapshots offline.

Options for generate:
  --out <file>       The file to write. Defaults to entitler_features.py.
  --key <key>        An API key with the plans:read scope. Defaults to ENTITLER_KEY.
  --base-url <url>   The API's base URL. Defaults to https://api.entitler.dev.
  --check            Check the file is up to date instead of writing it.
  --allow-empty      Write the file even when Entitler lists no features.

Options for snapshot-keys:
  --out <file>       The file to write. Defaults to entitler-snapshot-keys.json.
  --base-url <url>   The API's base URL. Defaults to https://api.entitler.dev.

  --help             Show this help.
"""

HEADER = "# Generated by entitler generate. Do not edit."
LINE_WIDTH = 88
_READ_FROM = re.compile(r"^# Read from .*$", re.MULTILINE)
_LINE_BREAK = re.compile("\r\n|[\r\n\x85\u2028\u2029]")
_UNSAFE = re.compile("[\x00-\x1f\x7f-\x9f\u2028\u2029]")
_CONTROL = re.compile("[\x00-\x1f\x7f-\x9f]")
_CONSTANT = re.compile(
    r"^([A-Za-z_][A-Za-z0-9_]*): Feature\[\w+\] = Feature(?:\.\w+)?\(\s*"
    r"(\"(?:[^\"\\\n]|\\.)*\"|'(?:[^'\\\n]|\\.)*')",
    re.MULTILINE,
)
_KINDS = {
    FeatureType.BOOLEAN: ("Boolean", "boolean"),
    FeatureType.CONFIG: ("Config", "config"),
    FeatureType.METERED: ("Metered", "metered"),
    FeatureType.GROUP: ("Group", "group"),
}
_COMMANDS = {
    "generate": ({"--out", "--key", "--base-url"}, {"--check", "--allow-empty"}),
    "snapshot-keys": ({"--out", "--base-url"}, set[str]()),
}


def _flat(text: str) -> str:
    return _CONTROL.sub("", _LINE_BREAK.sub(" ", text))


def _escape(char: str) -> str:
    code = ord(char)
    return f"\\x{code:02x}" if code < 0x100 else f"\\u{code:04x}"


def literal(text: str) -> str:
    """A Python string literal for `text`, quoted as the formatter would, its specials escaped."""
    quote = "'" if '"' in text and "'" not in text else '"'
    escaped = text.replace("\\", "\\\\").replace(quote, "\\" + quote)
    return quote + _UNSAFE.sub(lambda m: _escape(m.group()), escaped) + quote


def _doc_line(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return re.sub("[\x00-\x1f\x7f-\x9f]", lambda m: _escape(m.group()), escaped).rstrip()


def _base_name(key: str) -> str:
    words = [word for word in re.split(r"[^A-Za-z0-9]+", key) if word]
    name = "_".join(word.upper() for word in words)
    return f"_{name}" if not name or name[0].isdigit() else name


def constant_names(keys: Sequence[str], existing: str = "") -> dict[str, str]:
    """Each key's constant name: names in `existing` kept, then new ones in key order."""
    listed = set(keys)
    names: dict[str, str] = {}
    taken: set[str] = set()
    for match in _CONSTANT.finditer(existing):
        name = match.group(1)
        try:
            key = ast.literal_eval(match.group(2))
        except (ValueError, SyntaxError):
            continue
        if isinstance(key, str) and key in listed and key not in names and name not in taken:
            names[key] = name
            taken.add(name)
    for key in sorted(keys):
        if key in names:
            continue
        base = name = _base_name(key)
        count = 2
        while name in taken:
            name = f"{base}_{count}"
            count += 1
        names[key] = name
        taken.add(name)
    return names


def _leaves(key: str, by_key: Mapping[str, FeatureListing]) -> list[str]:
    found: list[str] = []
    seen = {key}

    def visit(members: Sequence[str]) -> None:
        for member in members:
            if member in seen:
                continue
            seen.add(member)
            feature = by_key.get(member)
            if feature is None:
                continue
            if feature.type == FeatureType.GROUP:
                visit(feature.includes)
            else:
                found.append(member)

    visit(by_key[key].includes)
    return found


def _doc(feature: FeatureListing) -> list[str]:
    lines = [_doc_line(_flat(feature.name).strip() or _flat(feature.key))]
    description = feature.description.strip()
    if description:
        lines += [
            "",
            *(_doc_line(_CONTROL.sub("", line)) for line in _LINE_BREAK.split(description)),
        ]
    unit = _flat(feature.unit).strip()
    if unit:
        lines += ["", _doc_line(f"Counted in {unit}.")]
    if feature.type == FeatureType.GROUP and feature.includes:
        lines += ["", _doc_line(f"Includes {', '.join(_flat(item) for item in feature.includes)}.")]
    if feature.archived:
        lines += ["", "Deprecated: Archived in Entitler."]
    if len(lines) == 1:
        return [f'"""{lines[0]}"""']
    return [f'"""{lines[0]}', *lines[1:], '"""']


def _assignment(name: str, feature: FeatureListing, members: list[str]) -> list[str]:
    kind = _KINDS.get(feature.type) if isinstance(feature.type, FeatureType) else None
    if kind is None:
        head = f"{name}: Feature[object] = Feature("
        args = [literal(feature.key), literal(str(feature.type))]
    else:
        head = f"{name}: Feature[{kind[0]}] = Feature.{kind[1]}("
        args = [literal(feature.key)]
        if feature.type == FeatureType.GROUP:
            quoted = [literal(member) for member in members]
            args.append(f"({quoted[0]},)" if len(quoted) == 1 else f"({', '.join(quoted)})")
    inline = f"{head}{', '.join(args)})"
    if len(inline) <= LINE_WIDTH:
        return [inline]
    hugged = f"    {', '.join(args)}"
    if len(hugged) <= LINE_WIDTH:
        return [head, hugged, ")"]
    lines = [head]
    for arg in args:
        if len(f"    {arg},") <= LINE_WIDTH or not arg.startswith("("):
            lines.append(f"    {arg},")
        else:
            lines += ["    (", *(f"        {member}," for member in members_of(arg)), "    ),"]
    return [*lines, ")"]


def members_of(group: str) -> list[str]:
    """The quoted members of a rendered tuple."""
    return [literal(item) for item in ast.literal_eval(group)]


def _read_from(source: FeatureList) -> str:
    if source.change is not None and source.release is None:
        catalogue = f"change {_flat(source.change)}"
    else:
        catalogue = f"release {'none' if source.release is None else source.release}"
    return f"# Read from {_flat(source.environment.name)}, {_flat(source.track.name)}, {catalogue}."


def render_features(source: FeatureList, *, existing: str = "") -> str:
    """Renders a module of typed feature constants, one per feature, sorted by key.

    Pass the current file as `existing`, so every feature keeps its constant's name and adding a
    feature never renames another.

    Example:
        ```python
        from entitler import EntitlerServer
        from entitler.cli import render_features

        with EntitlerServer(key) as server:
            Path("entitler_features.py").write_text(render_features(server.features()))
        ```
    """
    features = sorted(source.features, key=lambda feature: feature.key)
    by_key = {feature.key: feature for feature in features}
    names = constant_names([feature.key for feature in features], existing)
    lines = [HEADER, _read_from(source), '"""The features of the Entitler catalogue."""', ""]
    if features:
        kinds = sorted({_KINDS[f.type][0] for f in features if isinstance(f.type, FeatureType)})
        lines += [f"from entitler import {', '.join(sorted([*kinds, 'Feature']))}", ""]
        for feature in features:
            members = _leaves(feature.key, by_key) if feature.type == FeatureType.GROUP else []
            lines += [*_assignment(names[feature.key], feature, members), *_doc(feature), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def same_features(first: str, second: str) -> bool:
    """True when two generated files hold the same features, whichever release they came from."""
    return _READ_FROM.sub("", first) == _READ_FROM.sub("", second)


def _holds_constants(text: str) -> bool:
    return _CONSTANT.search(text) is not None


def _plural(count: int, noun: str) -> str:
    return f"1 {noun}" if count == 1 else f"{count} {noun}s"


def _failure(error: Exception) -> str:
    message = str(error).removesuffix(".")
    if isinstance(error, APIError):
        code: str | None = str(error.code)
    elif isinstance(error, EntitlerTimeoutError):
        code = "timed_out"
    elif isinstance(error, EntitlerConnectionError):
        code = "connection_failed"
    else:
        code = None
    return f"Entitler request failed: {message}{'' if code is None else f' ({code})'}."


def _parse(command: str, rest: Sequence[str]) -> dict[str, str | bool] | str:
    valued, flags = _COMMANDS[command]
    options: dict[str, str | bool] = {}
    index = 0
    while index < len(rest):
        arg = rest[index]
        flag, has_value, inline = arg.partition("=")
        if flag in flags and not has_value:
            options[flag[2:]] = True
        elif flag in valued:
            if not has_value:
                index += 1
                inline = rest[index] if index < len(rest) else ""
            if not inline:
                return f"Pass a value with {flag}."
            options[flag[2:]] = inline
        else:
            return f"Unknown option {arg}.\n\n{USAGE}"
        index += 1
    return options


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as file:
            file.write(text)
        Path(temporary).replace(path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def _server(key: str, options: Mapping[str, str | bool]) -> object:
    from ._clients import EntitlerServer

    base_url = options.get("base-url")
    try:
        if isinstance(base_url, str):
            return EntitlerServer(key, cache=None, base_url=base_url)
        return EntitlerServer(key, cache=None)
    except (TypeError, ValueError) as error:
        return str(error)


def _generate(options: Mapping[str, str | bool], env: Mapping[str, str]) -> tuple[int, str]:
    from ._clients import EntitlerServer

    path = Path(str(options.get("out", "entitler_features.py")))
    key = options.get("key") or env.get("ENTITLER_KEY", "")
    if not isinstance(key, str) or not key.strip():
        return (
            1,
            "Provide an API key with --key or set ENTITLER_KEY. "
            "The key needs the plans:read scope.",
        )
    server = _server(key, options)
    if isinstance(server, str):
        return 1, server
    assert isinstance(server, EntitlerServer)  # noqa: S101 - built above
    with server:
        try:
            source = server.features()
        except (APIError, EntitlerConnectionError, EntitlerTimeoutError) as error:
            return 1, _failure(error)
        except (TypeError, ValueError) as error:
            return 1, str(error)
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    rendered = render_features(source, existing=existing or "")
    count = _plural(len(source.features), "feature")
    if options.get("check"):
        if existing is not None and same_features(existing, rendered):
            return 0, f"{path} is up to date with {count}."
        return 1, f"{path} is out of date. Run entitler generate to update it."
    if (
        not source.features
        and not options.get("allow-empty")
        and existing
        and _holds_constants(existing)
    ):
        return 1, (
            f"Entitler listed no features, so {path} was left as it is. "
            "Check the key's environment, or pass --allow-empty."
        )
    _write(path, rendered)
    return 0, f"Wrote {count} to {path}."


def _snapshot_keys(options: Mapping[str, str | bool]) -> tuple[int, str]:
    from ._clients import EntitlerServer

    path = Path(str(options.get("out", "entitler-snapshot-keys.json")))
    server = _server("snapshot-keys", options)
    if isinstance(server, str):
        return 1, server
    assert isinstance(server, EntitlerServer)  # noqa: S101 - built above
    with server:
        try:
            keys, raw = server._driver.run(snapshot_keys(server._driver.engine, None))
        except (APIError, EntitlerConnectionError, EntitlerTimeoutError) as error:
            return 1, _failure(error)
    if not keys.keys:
        return 1, f"Entitler published no snapshot keys, so {path} was left as it is."
    _write(path, json.dumps({"keys": raw["keys"]}, indent=2, ensure_ascii=False) + "\n")
    return 0, f"Wrote {_plural(len(keys.keys), 'snapshot key')} to {path}."


def main(
    argv: Sequence[str] | None = None,
    *,
    env: Mapping[str, str] | None = None,
    stdout: TextIO | None = None,
    stderr: TextIO | None = None,
) -> int:
    """Runs the command line with `argv` (without the program name), answering the exit code."""
    args = list(sys.argv[1:] if argv is None else argv)
    out = sys.stdout if stdout is None else stdout
    err = sys.stderr if stderr is None else stderr
    if "--help" in args:
        out.write(USAGE)
        return 0
    if not args or args[0] not in _COMMANDS:
        err.write(USAGE if not args else f"Unknown command {args[0]}.\n\n{USAGE}")
        return 1
    options = _parse(args[0], args[1:])
    if isinstance(options, str):
        err.write(options if options.endswith("\n") else options + "\n")
        return 1
    if args[0] == "generate":
        code, message = _generate(options, os.environ if env is None else env)
    else:
        code, message = _snapshot_keys(options)
    (out if code == 0 else err).write(message + "\n")
    return code
